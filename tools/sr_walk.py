"""The screen reader's walk (fm1-reader's audit): a host-simulator script that visits every page, part, effect,
preset, held key and pad, asks WHERE on each and turns each knob through its values, so every text the reader can
be sent is said once. tools/sr_audit.sh runs it with FM1B_SAID_LOG and audits the log.
    python3 tools/sr_walk.py > build/sr/walk.txt"""

L = []
def c(*cmds):
    L.extend(cmds)

def sweep(knobs=(1, 2, 3, 4), steps=30):
    """each knob all the way down, then up a detent at a time (each settles: the reader hears each value)"""
    for k in knobs:
        c(f"turn K{k} -80 4", "wait 150")
        for _ in range(steps):
            c(f"turn K{k} 1 10", "wait 140")

def here(knobs=(1, 2, 3, 4), steps=30):
    c("wait 260", "where", "wait 60")
    sweep(knobs, steps)

c("# generated by tools/sr_walk.py: the screen reader's walk (tools/sr_audit.sh)", "wait 2600", "tap HOME",
  "wait 300", "listen", "wait 200")
# HOME: PERFORM and GENERATOR
for _ in range(2):
    here()
    c("tap HOME")
# FX: each effect in turn on the slot, each of its parts (MB COMP has six)
c("tap FX")
for t in range(14):
    c("turn PRESET 1 10")
    for part in range(6):
        here(steps=20)
        c("tap FX")
    c("tap HOME", "wait 100", "tap FX")
# GLOBAL: MIDI, PITCH (not RESET ALL), BT AUDIO (not SCAN, CONNECT), CHANNEL
c("tap GLO")
for g, knobs in enumerate([(1, 2, 3, 4), (1, 2, 3), (1, 2), (1, 2, 3, 4)]):
    here(knobs, 20)
    c("tap GLO")
# EDIT: the kick's parts and presets, the snare's and the hat's
c("tap EDIT")
for drum, parts in enumerate([11, 2, 2]):
    for _ in range(8):
        c("turn PRESET 1 10", "wait 160")
    for p in range(parts):
        here(steps=20)
        c("turn ALGO 1 10")
    c("tap EDIT")
# LFO (the mixer): LEVELS, GROOVE
c("tap LFO")
for _ in range(2):
    here()
    c("tap LFO")
# SEQ: its lanes
c("tap SEQ")
for _ in range(5):
    here(steps=16)
    c("tap SEQ")
# ENV: tap tempo
c("tap HOME", "wait 100", "tap ENV")
here((1, 2, 4), 20)
# ARP: each black key's effect, its parts
c("tap ARP")
for b in range(11):
    c(f"tapkey b{b}", "wait 100")
    for part in range(3):
        here(steps=12)
        c("tap ARP")
for _ in range(14):
    c("turn PRESET 1 10", "wait 160")
# a white key held: its loop, its slice effect (FX while held); a pad held
c("tap HOME", "wait 200", "key w3 down", "wait 400")
here()
c("tap FX")
here()
c("key w3 up", "wait 300")
for p in range(11):
    c(f"key b{p} down", "wait 300")
    here(steps=16)
    c(f"key b{p} up", "wait 200")
# the SEL card, play and stop
c("tap SEL", "wait 400", "tap SEL", "wait 300", "tap PLAY", "wait 400", "tap PLAY", "wait 400")
print("\n".join(L))
