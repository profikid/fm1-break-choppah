"""The custom break (PRD A-60) as the break manager page sends it: a WAV made into a bank of one slot exactly as the
built-in breaks are (tools/prep_breaks.py), and the SysEx frames that write it (ui/main.c app_sysex). For the tests:
    python3 tools/cu_frames.py FILE.wav BPM NAME > build/custom.txt     a host-simulator scenario that uploads it
    python3 tools/cu_frames.py --bank FILE.wav BPM NAME OUT.bin         just the bank image"""
import argparse
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))
import prep_breaks as pb  # noqa: E402

CHUNK = 512


def pack7(b):
    out = bytearray()
    for i in range(0, len(b), 7):
        g = b[i:i + 7]
        out.append(sum(((v >> 7) & 1) << j for j, v in enumerate(g)))
        out += bytes(v & 0x7F for v in g)
    return bytes(out)


def frame(cmd, data=b""):
    return bytes([0xF0, 0x7D, 0x43, 0x48, cmd]) + pack7(data) + bytes([0xF7])


def bank(wav, bpm, name):
    args = argparse.Namespace(bars=2, slices=16, break_slices=16, rate=22050, transients=True, loudness=-16.0,
                              name_prefix="")
    return pb.build_bank([pb.prepare(f"{wav}:{bpm}:2:{name}", args)])


def frames(img):
    u32 = lambda v: v.to_bytes(4, "little")  # noqa: E731
    yield "begin", frame(2, u32(len(img)))
    for off in range(16, len(img), CHUNK):
        yield "data", frame(3, u32(off) + img[off:off + CHUNK])
    yield "commit", frame(4, img[:16])


def hexs(f):
    return " ".join(f"{v:02X}" for v in f)


if __name__ == "__main__":
    a = sys.argv[1:]
    if a and a[0] == "--bank":
        Path(a[4]).write_bytes(bank(a[1], float(a[2]), a[3]))
        raise SystemExit
    img = bank(a[0], float(a[1]), a[2])
    print(f"# generated by tools/cu_frames.py: {a[2]} ({len(img)} B) uploaded as the custom break")
    for kind, f in frames(img):
        print(f"sysex {hexs(f)}")
        print("wait 20" if kind == "data" else "wait 200")
