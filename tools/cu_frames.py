"""The pack (PRD S-003) as the break manager page sends it: WAVs made into a bank exactly as the built-in breaks are
(tools/prep_breaks.py), and the SysEx frames that write it into one of the pack's two banks (ui/main.c app_sysex). For
the tests:
    python3 tools/cu_frames.py FILE.wav BPM NAME > build/custom.txt     a host-simulator scenario that uploads it
    python3 tools/cu_frames.py --bank FILE.wav BPM NAME OUT.bin         just the bank image
    python3 tools/cu_frames.py [--to 2] [--out OUT.bin] FILE BPM NAME [FILE BPM NAME ...]
                                                                       several breaks in one bank (--to 2: bank 2)"""
import argparse
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))
import prep_breaks as pb  # noqa: E402

CHUNK = 448  # as the page (breaks.html CHUNK): 521 bytes a frame on the wire


def pack7(b):
    out = bytearray()
    for i in range(0, len(b), 7):
        g = b[i:i + 7]
        out.append(sum(((v >> 7) & 1) << j for j, v in enumerate(g)))
        out += bytes(v & 0x7F for v in g)
    return bytes(out)


def frame(cmd, data=b"", to=1):
    return bytes([0xF0, 0x7D, 0x43, 0x48, cmd | (to - 1) << 4]) + pack7(data) + bytes([0xF7])


def no_at(img):
    """bank 2 (PLAT_XDATA1): "AT" never at a sector's 0xF06 (the update loader's record): the byte there nudged (one
    ADPCM step, inaudible), the CRC made again. The page does the same"""
    img = bytearray(img)
    for q in range(0xF06, len(img) - 1, 4096):
        if img[q:q + 2] == b"AT":
            img[q] ^= 1
    n = int.from_bytes(img[8:12], "little")
    img[12:16] = pb.zlib.crc32(bytes(img[16:16 + n])).to_bytes(4, "little")
    return bytes(img)


def bank(*specs, to=1):
    """specs: (wav, bpm, name), ...: one bank of them, in that order"""
    if specs and not isinstance(specs[0], tuple):
        specs = (specs,)
    args = argparse.Namespace(bars=2, slices=16, break_slices=16, rate=22050, transients=True, loudness=-16.0,
                              name_prefix="")
    img = pb.build_bank([pb.prepare(f"{w}:{b}:2:{n}", args) for w, b, n in specs])
    return no_at(img) if to == 2 else img


def frames(img, to=1):
    u32 = lambda v: v.to_bytes(4, "little")  # noqa: E731
    yield "begin", frame(2, u32(len(img)), to)
    for off in range(16, len(img), CHUNK):
        yield "data", frame(3, u32(off) + img[off:off + CHUNK], to)
    yield "commit", frame(4, img[:16], to)


def hexs(f):
    return " ".join(f"{v:02X}" for v in f)


if __name__ == "__main__":
    a = sys.argv[1:]
    if a and a[0] == "--bank":
        Path(a[4]).write_bytes(bank(a[1], float(a[2]), a[3]))
        raise SystemExit
    to, out = 1, None
    while a and a[0] in ("--to", "--out"):
        if a[0] == "--to":
            to = int(a[1])
        else:
            out = a[1]
        a = a[2:]
    specs = tuple((a[i], float(a[i + 1]), a[i + 2]) for i in range(0, len(a), 3))
    img = bank(*specs, to=to)
    if out:
        Path(out).write_bytes(img)
    print(f"# generated by tools/cu_frames.py: {', '.join(s[2] for s in specs)} ({len(img)} B) into bank {to}")
    for kind, f in frames(img, to):
        print(f"sysex {hexs(f)}")
        print("wait 20" if kind == "data" else "wait 200")
