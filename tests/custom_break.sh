# The custom break (PRD A-60) end to end in the host simulator: a WAV made into a bank as the break manager page
# makes it (tools/cu_frames.py, prep_breaks.py's way), uploaded over SysEx, checked, loaded first and at power-on,
# read back byte for byte, deleted. Needs ./build.sh --host first.
#   tests/custom_break.sh
set -e
cd "$(dirname "$0")/.."
O=app/build/custom
mkdir -p "$O"
W=breaks/classics/rotary_connection_life_could.wav
python3 tools/cu_frames.py --bank "$W" 99.81 "LIFE COULD" "$O/bank.bin"
N=$(wc -c < "$O/bank.bin")
{
cat <<'S'
# (generated by tests/custom_break.sh)
wait 2600
tap HOME
wait 300
expect n_user 0
expect n_breaks 8
sysex_out
sysex F0 7D 43 48 01 F7
wait 50
expect_sysex F0 7D 43 48 41 00 20 01 00 00 0E 00 60 00 00 00 00 00 00 00 F7
tap PLAY
wait 300
sysex F0 7D 43 48 02 03 55 4F 00 00 F7
wait 100
expect_sysex F0 7D 43 48 42 01 F7
said_none
tap PLAY
wait 300
S
python3 tools/cu_frames.py "$W" 99.81 "LIFE COULD" | tail -n +2
cat <<'S'
expect n_user 1
expect n_breaks 9
expect brk 0
shot cu_loaded.png
tap PLAY
wait 1500
expect peak_db_min -30
tap PLAY
wait 300
reboot
wait 2600
tap HOME
wait 300
expect n_user 1
expect brk 0
S
off=0
while [ $off -lt $N ]; do
    echo "sysex $(python3 -c "
import sys; sys.path.insert(0,'tools'); import cu_frames as c
print(c.hexs(c.frame(5, ($off).to_bytes(4,'little') + (256).to_bytes(4,'little'))))")"
    off=$((off + 256))
done
cat <<'S'
wait 100
sysex_log off
sysex F0 7D 43 48 06 F7
wait 300
expect n_user 0
expect n_breaks 8
expect brk 0
S
} > "$O/custom.txt"
sed -i "s|^sysex_out\$|sysex_log $PWD/$O/out.syx\nsysex_out|" "$O/custom.txt"
rm -f "$O/out.syx"
app/build/host/choppah_host "$O/custom.txt" app/build/scenarios > "$O/run.log" 2>&1 || { grep -E "FAIL|host:" "$O/run.log"; exit 1; }
grep -E "FAIL|host:" "$O/run.log"
python3 - "$O/out.syx" "$O/bank.bin" <<'P'
import sys
raw, img = open(sys.argv[1], "rb").read(), open(sys.argv[2], "rb").read()
got = bytearray(len(img))
seen = 0
for f in raw.split(b"\xf0")[1:]:
    f = f.split(b"\xf7")[0]
    if f[:4] != bytes([0x7D, 0x43, 0x48, 0x45]) or f[4] != 0:
        continue
    p, u = f[5:], bytearray()
    for i in range(0, len(p), 8):
        hi = p[i]
        u += bytes(p[i + j] | ((hi >> (j - 1)) & 1) << 7 for j in range(1, min(8, len(p) - i)))
    off = int.from_bytes(u[:4], "little")
    d = u[4:]
    n = min(len(d), len(img) - off)
    got[off:off + n] = d[:n]
    seen += 1
assert seen and bytes(got) == img, f"read back differs ({seen} frames)"
print(f"custom_break: {len(img)} B uploaded, loaded, kept at power-on, read back the same in {seen} frames, deleted")
P
