# The pack arriving (PRD S-034) in the host simulator: a pack over both banks whose BEGINs say its name and where each
# bank is in it (tools/cu_frames.py --name, as breaks.html and fm1link.js send it since 1.7.1): the upload screen
# says RECEIVING and the name, its bar fills across both banks, PACK LOADED when the last checks, then the slicer
# again; a bank sent the old way (the size alone) is "PACK"; a touch hides the screen and does nothing else; a send that
# dies leaves PACK NOT LOADED after 5 s. Shots in app/build/pack_screen (up_*.png). Needs ./build.sh --host first.
#   tests/pack_screen.sh
set -e
cd "$(dirname "$0")/.."
O=app/build/pack_screen
mkdir -p "$O"
C=breaks/classics
python3 tools/cu_frames.py --out "$O/b1.bin" $C/lyn_collins_think_about_it.wav 113.78 "P THINK" > /dev/null
python3 tools/cu_frames.py --to 2 --out "$O/b2.bin" $C/the_winstons_amen_brother.wav 141.82 "P AMEN" > /dev/null
N1=$(wc -c < "$O/b1.bin")
N2=$(wc -c < "$O/b2.bin")
python3 tools/cu_frames.py --name "Amen Classics" --total $((N1 + N2)) $C/lyn_collins_think_about_it.wav 113.78 "P THINK" > "$O/b1.txt"
python3 tools/cu_frames.py --to 2 --name "Amen Classics" --total $((N1 + N2)) --before $N1 \
    $C/the_winstons_amen_brother.wav 141.82 "P AMEN" > "$O/b2.txt"
python3 tools/cu_frames.py $C/lyn_collins_think_about_it.wav 113.78 "P THINK" > "$O/old.txt"
python3 - "$O" <<'P'
import sys
o = sys.argv[1]
rd = lambda f: [l for l in open(f"{o}/{f}").read().splitlines() if not l.startswith("#")]
b1, b2, old = rd("b1.txt"), rd("b2.txt"), rd("old.txt")
h1, h2 = len(b1) // 2, len(b2) // 2
s = ["# (generated by tests/pack_screen.sh)", "wait 2600", "tap HOME", "wait 300", "listen"]
s += b1[:6] + ["wait 100", "said RECEIVING Amen Classics", "shot up_start.png"]
s += b1[6:h1] + ["shot up_mid.png"] + b1[h1:] + b2[:h2] + ["shot up_bank2.png"] + b2[h2:]
s += ["wait 100", "said PACK LOADED Amen Classics", "shot up_done.png", "expect n_user 2",
      "wait 3000", "shot up_after.png"]
s += old[:6] + ["wait 100", "said RECEIVING PACK", "tap PLAY", "wait 200", "expect playing 0", "shot up_hidden.png"]
s += old[6:] + ["wait 300", "expect n_user 2"]   # (bank 2 keeps its break)
s += old[:6] + ["wait 5500", "said PACK NOT LOADED"]
open(f"{o}/pack_screen.txt", "w").write("\n".join(s) + "\n")
P
app/build/host/choppah_host "$O/pack_screen.txt" "$O" > "$O/run.log" 2>&1 || { grep -E "FAIL|host:" "$O/run.log"; exit 1; }
grep -E "FAIL" "$O/run.log" && exit 1
echo "pack_screen: the name and the bar over both banks, PACK LOADED, the old BEGIN's PACK, a touch hides it, a dead send warns"
