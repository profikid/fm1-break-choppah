# The pack (PRD S-003) end to end in the host simulator: three breaks into bank 1 (the data area) and two into bank 2
# (PLAT_XDATA1) as the break manager page sends them (tools/cu_frames.py, prep_breaks.py's way), INFO's answer, the
# pack first in the break list (bank 1's, then bank 2's, then the built-in eight), a break of bank 2 played, both kept at
# power-on, bank 2 read back byte for byte, a write that would put "AT" at a sector's 0xF06 refused (the update
# loader's record), each bank deleted. Needs ./build.sh --host first.
#   tests/pack.sh
set -e
cd "$(dirname "$0")/.."
O=app/build/pack
mkdir -p "$O"
C=breaks/classics
python3 tools/cu_frames.py --out "$O/b1.bin" $C/lyn_collins_think_about_it.wav 113.78 "P THINK" \
    $C/incredible_bongo_band_apache.wav 114.78 "P APACHE" $C/lightnin_rod_sport.wav 120.69 "P SPORT" > "$O/b1.txt"
python3 tools/cu_frames.py --to 2 --out "$O/b2.bin" $C/the_winstons_amen_brother.wav 141.82 "P AMEN" \
    $C/jimmy_mcgriff_the_worm.wav 109.79 "P WORM" > "$O/b2.txt"
N1=$(wc -c < "$O/b1.bin")
N2=$(wc -c < "$O/b2.bin")
INFO=$(python3 -c "
import struct, sys; sys.path.insert(0, 'tools'); import cu_frames as c
v = struct.pack('<6I', 2 | 5 << 16 | 63 << 24, 63 * 4096, $N1, 2 | 3 << 8 | 2 << 16, 23 * 4096, $N2)
print(c.hexs(bytes([0xF0, 0x7D, 0x43, 0x48, 0x41, 0]) + c.pack7(v) + bytes([0xF7])))")
BEGIN2=$(python3 -c "
import sys; sys.path.insert(0, 'tools'); import cu_frames as c
print(c.hexs(c.frame(2, (8192).to_bytes(4, 'little'), to=2)))")
AT=$(python3 -c "
import sys; sys.path.insert(0, 'tools'); import cu_frames as c
print(c.hexs(c.frame(3, (0xF00).to_bytes(4, 'little') + bytes(6) + b'AT', to=2)))")
{
cat <<'S'
# (generated by tests/pack.sh)
wait 2600
tap HOME
wait 300
expect n_user 0
expect n_breaks 8
S
tail -n +2 "$O/b1.txt"
cat <<'S'
expect n_user 3
expect n_breaks 11
expect brk 0
S
tail -n +2 "$O/b2.txt"
cat <<S
expect n_user 5
expect n_breaks 13
expect brk 0
sysex_out
sysex F0 7D 43 48 01 F7
wait 50
expect_sysex $INFO
listen
turn ALGO 1
wait 300
said P APACHE
turn ALGO 2
wait 300
said P AMEN
expect brk 3
tap PLAY
wait 1500
expect peak_db_min -30
tap PLAY
wait 300
turn ALGO 2
wait 300
said AMEN
expect brk 5
reboot
wait 2600
tap HOME
wait 300
expect n_user 5
expect n_breaks 13
expect brk 0
S
off=0
while [ $off -lt $N2 ]; do
    echo "sysex $(python3 -c "
import sys; sys.path.insert(0,'tools'); import cu_frames as c
print(c.hexs(c.frame(5, ($off).to_bytes(4,'little') + (256).to_bytes(4,'little'), to=2)))")"
    off=$((off + 256))
done
cat <<S
wait 100
sysex_log off
sysex $BEGIN2
wait 300
sysex_out
sysex $AT
wait 50
expect_sysex F0 7D 43 48 53 02 F7
sysex F0 7D 43 48 16 F7
wait 300
expect n_user 3
expect n_breaks 11
sysex F0 7D 43 48 06 F7
wait 300
expect n_user 0
expect n_breaks 8
expect brk 0
S
} > "$O/pack.txt"
sed -i "0,/^sysex_out\$/s|^sysex_out\$|sysex_log $PWD/$O/out.syx\nsysex_out|" "$O/pack.txt"
rm -f "$O/out.syx"
app/build/host/choppah_host "$O/pack.txt" app/build/scenarios > "$O/run.log" 2>&1 || { grep -E "FAIL|host:" "$O/run.log"; exit 1; }
grep -E "FAIL|host:" "$O/run.log"
python3 - "$O/out.syx" "$O/b2.bin" <<'P'
import sys
raw, img = open(sys.argv[1], "rb").read(), open(sys.argv[2], "rb").read()
got, seen = bytearray(len(img)), 0
for f in raw.split(b"\xf0")[1:]:
    f = f.split(b"\xf7")[0]
    if f[:4] != bytes([0x7D, 0x43, 0x48, 0x55]) or f[4] != 0:
        continue
    p, u = f[5:], bytearray()
    for i in range(0, len(p), 8):
        u += bytes(p[i + j] | ((p[i] >> (j - 1)) & 1) << 7 for j in range(1, min(8, len(p) - i)))
    off = int.from_bytes(u[:4], "little")
    n = min(len(u) - 4, len(img) - off)
    got[off:off + n] = u[4:4 + n]
    seen += 1
assert seen and bytes(got) == img, f"bank 2 read back differs ({seen} frames)"
assert all(img[q:q + 2] != b"AT" for q in range(0xF06, len(img) - 1, 4096)), "AT at a sector's 0xF06"
print(f"pack: 5 breaks (bank 1 {len(open(sys.argv[2].replace('b2', 'b1'), 'rb').read())} B, bank 2 {len(img)} B) "
      f"uploaded, listed first, played, kept at power-on, bank 2 read back the same in {seen} frames, AT refused, deleted")
P
